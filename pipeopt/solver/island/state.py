"""Стан острова: температура відчаю, частка пройденого, пороги.

Усе, що відповідає на питання «де зараз пошук» — і нічого, що його
рухає. Саме тому ці величини лежать окремо: від них залежать одинадцять
рішень у решті модулів (ліміт застою, інтервал міграції, поріг
«авантюриста», заморозка консенсусу, ширина променя), і коли вони
розкидані по тексту, побачити цю залежність неможливо.
"""

from dataclasses import dataclass




@dataclass
class AppliedKick:
    """Результат кіка, який дійшов до розв'язки.

    Сім значень, які потрібні всім п'яти гілкам прийняття. Поки гілки
    жили всередині одного методу, вони брали їх із замикання; після
    виносу довелося б передавати по вісім аргументів у кожну. Окремий
    тип робить набір видимим і дозволяє додати похідне поле
    (`learns_size`) в одному місці замість п'яти.
    """

    strategy: str
    use_bandit: bool
    #: `KickResult` від стратегії — потрібен заради `failed_pipe` і `used_pct`.
    result: object
    solution: list
    cost: float
    score: float
    round_idx: int

    @property
    def used_pct(self):
        return self.result.used_pct

    @property
    def learns_size(self):
        """Чи ця стратегія навчає розмір свого кроку за JADE.

        Перевірка `used_pct is not None` повторювалась у п'яти гілках;
        тут вона названа один раз.
        """
        return self.result.used_pct is not None


class IslandState:
    """Де зараз пошук: температура, прогрес, пороги підозри."""

    #: Інтервал міграції, коли бюджет симуляцій не обмежений.
    DEFAULT_MIGRATION_INTERVAL = 15000
    #: Нижня межа інтервалу — щоб міграція не відбувалась щороунду.
    MIN_MIGRATION_INTERVAL = 1000
    #: Частка прогону, після якої воркери синхронізуються вп'ятеро частіше.
    LATE_MIGRATION_RATIO = 0.8

    @property
    def temperature(self):
        """«Температура відчаю»: наскільки давно не було прогресу.

        Формула стояла дослівно у двох місцях — у `_apply_kick` під іменем
        `real_T` і в блоці міграції під іменем `T`. Одне джерело прибирає
        ризик, що вони розійдуться: обидва місця вирішують те саме —
        наскільки агресивно поводитись при застої.
        """
        return min(1.0, self.stagnation_counter / max(1, self.stag_limit * 3.0))

    #: Нижче цієї температури пошук вважається холодним: він полірує, а
    #: не досліджує, і тільки тоді заморозка консенсусу має сенс.
    COLD_TEMPERATURE = 0.2

    @property
    def temperature_is_cold(self):
        return self.acceptance.effective_temperature(
            self.temperature) < self.COLD_TEMPERATURE

    def progress_of(self, sims, elapsed, time_budget):
        """Частка пройденого прогону — за тим бюджетом, який ближче до кінця.

        Раніше це було «або симуляції, або час»: при заданому `max_sims`
        час не враховувався взагалі. Прогін, обмежений годинником (а на
        великих мережах практично будь-який: квота XLARGE — 30 млн
        симуляцій, тобто близько 20 діб на одному ядрі), давав частку
        близько нуля до самого кінця. А від неї залежать **одинадцять**
        рішень: перехід у другу половину прогону (`is_late_game`), ліміт
        застою, інтервал міграції, поріг «авантюриста», вікно
        серцебиття, заморозка консенсусу, дистанція різноманітності
        променя, його динамічна ширина. Тобто такий прогін від початку
        до кінця поводився так, ніби щойно почався.

        Тепер береться максимум з двох часток. Там, де скінченний лише
        один бюджет, результат не змінюється: другий доданок дає 0.
        """
        by_sims = (sims / max(1, self.max_sims)
                   if self.max_sims != float('inf') else 0.0)
        by_time = (elapsed / time_budget
                   if time_budget and time_budget != float('inf') else 0.0)
        return min(1.0, max(by_sims, by_time))

    #: Частка бюджету, дорожче за яку **раунд** не має права коштувати.
    #:
    #: Це заміна дільнику `CANDIDATE_DIVISOR` за класом мережі, і замінює
    #: вона таблицю величиною, яку прогін міряє сам: ціною раунду в
    #: симуляціях. Розміру мережі у правилі немає — є лише те, скільки
    #: раунд щойно з'їв.
    #:
    #: Звідки 0.04: раунд коштує 0.13 % бюджету на Ханої, 0.3 % на
    #: Фоссі, 16 % на Балермі й 20 % на сітці 16×16, а заміряні найкращі
    #: варіанти лежать у смузі 2-8 % (журнал, етап 26).
    ROUND_BUDGET_SHARE = 0.04

    #: Наскільки звужується раунд за один крок. Не параметр задачі, а
    #: крок регулятора: менший — повільніша збіжність, більший —
    #: перестрибує. Заміряно, що поступове звуження краще за стрибок
    #: одразу до кінцевої ширини (2.1157 проти 2.1277 M$ на Балермі).
    ROUND_SHRINK_STEP = 0.7

    def round_cost_limit(self, time_budget):
        """Скільки симуляцій раунду дозволено з'їсти.

        Бюджет прогону береться в симуляціях. Коли його немає (прогін
        обмежений годинником), він рахується з **заміряної** швидкості
        симулятора, а не з таблиці за класом мережі: інакше правило
        протягло б назад те, що прибирає.
        """
        budget = self.max_sims
        if budget == float('inf'):
            budget = max(1.0, time_budget * self.ctx.sim_speed)
        return self.ROUND_BUDGET_SHARE * budget

    def narrow_round(self, spent):
        """Звузити раунд, якщо він вийшов дорожчим за дозволене.

        Правило **одностороннє**: воно лише звужує й ніколи не розширює.
        Заміряно тільки звуження (на великих мережах воно дає -1.9 % на
        Балермі й -0.25 % на сітці, 3 зерна з 3); розширення на малих
        мережах не міряв ніхто, і закладати неміряний напрямок у правило
        не можна. Саме тому на Ханої та Фоссі прогін лишається побітово
        тим самим: там раунд коштує 0.13-0.3 % бюджету й під поріг не
        підпадає.
        """
        if spent <= self._round_cost_limit:
            return False
        floor = self.ctx.profile.MIN_CANDIDATES
        if self.SINGLE_CANDIDATES <= floor:
            return False
        self.SINGLE_CANDIDATES = max(
            floor, int(self.SINGLE_CANDIDATES * self.ROUND_SHRINK_STEP))
        return True

    def _migration_interval(self):
        """Через скільки симуляцій воркер знову дивиться на сусідів.

        Раніше цей розрахунок стояв у двох місцях `run()` і був записаний
        двома різними виразами: `max_sims // 100` перед циклом і
        `(max_sims // 20) // 5` усередині. Це те саме число — тепер воно
        обчислюється один раз і в одному місці.
        """
        if self.max_sims == float('inf'):
            return self.DEFAULT_MIGRATION_INTERVAL
        base_interval = self.max_sims // 20
        if self.progress_ratio > self.LATE_MIGRATION_RATIO:
            return max(self.MIN_MIGRATION_INTERVAL, base_interval // 5)
        return max(self.MIN_MIGRATION_INTERVAL,
                   int(base_interval * (1.0 - 0.6 * self.progress_ratio)))

    #: Частка рекорду, більше за яку виграш вважається суттєвим і повністю
    #: скидає застій. Менший виграш лише зменшує лічильник на 2.
    RECORD_RESET_FRACTION = 0.005

    #: Виграш, більший за цю частку рекорду, вважається підозрілим і
    #: перевіряється на артефакт симуляції (`is_ghost_solution`).
    GHOST_SUSPICION_FRACTION = 0.02

    #: Стеля збурення: жоден кік не чіпає більше за цю частку мережі.
    MAX_PERTURB_FRACTION = 0.50

    def _is_ghost_gain(self, cost, solution):
        """Чи виграш завеликий, щоб бути справжнім.

        Та сама перевірка стояла дослівно у `_apply_swap` і в
        `_beam_search_and_update`, з однаковою неназваною 0.02. Порядок
        обчислень збережено: `is_ghost_solution` виконує симуляції, тому
        вона й далі викликається **лише** при підозріло великому виграші.
        """
        if (self.run_best_cost - cost) <= self.run_best_cost * self.GHOST_SUSPICION_FRACTION:
            return False
        return self.ctx.is_ghost_solution(solution)

    @staticmethod
    def _stagnation_after_record(diff, new_best_cost, current_counter):
        """Новий лічильник застою після оновлення рекорду.

        Порог рахується від **нового** рекорду, а не від старого — так було
        в обох місцях, де це правило застосовується, і так лишається.
        Різниця між двома варіантами — 0.5 %, тому прогоном вона невидима;
        зафіксована тестом `test_stagnation_threshold_is_measured_against_
        the_new_best_not_the_old`.
        """
        if diff > new_best_cost * IslandState.RECORD_RESET_FRACTION:
            return 0
        return max(0, current_counter - 2)
